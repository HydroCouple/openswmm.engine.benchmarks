#!/usr/bin/env python3
"""CaseSpec -> 1D SWMM .inp deck (SI / CMS, RECT_OPEN prismatic channel).

Deck shape: nx conduits of length dx between nx+1 nodes at x_i = i*dx with
inverts z(x_i); constant upstream inflow Q = q*W1d; downstream OUTFALL
(FIXED stage / FREE) or plain junctions for closed basins (dam breaks,
Thacker). Initial depths via the [JUNCTIONS] InitDepth column.

Fairness rules enforced here (README): one normalized [OPTIONS] block — only
FLOW_ROUTING differs between 1D solver columns; frictionless cases use
n = 1e-8 so the identical deck also satisfies the legacy engine's n > 0
validation (Sf ~ n^2 — physically negligible).
"""
from __future__ import annotations

import numpy as np

from .casespec import CaseSpec, SolverSpec
from .extract import link_id, node_id
from .genrefs import reference_blocks

N_FRICTIONLESS = 1e-8


def _hms(seconds: float) -> str:
    s = int(round(seconds))
    return f"{s // 3600}:{(s % 3600) // 60:02d}:{s % 60:02d}"


def ref_h_max(case: CaseSpec) -> float:
    return max(float(np.max(h)) for _, h, _ in
               reference_blocks(case, density=1).values())


def max_depth(case: CaseSpec) -> float:
    x = np.linspace(0.0, case.L, case.nx + 1)
    z = case.z(x)
    if case.h_max is not None:
        # Explicit sizing (bend family): the reference is a pinned 2D run
        # that may not exist yet — deck generation must not depend on it.
        return float(z.max() - z.min() + 3.0 * case.h_max)
    return float(z.max() - z.min() + 3.0 * ref_h_max(case))


def min_conduit_slope(case: CaseSpec, nx: int | None = None) -> float:
    nx = nx or case.nx
    x = np.linspace(0.0, case.L, nx + 1)
    z = case.z(x)
    return float(np.min((z[:-1] - z[1:]) / (case.L / nx)))


def build_inp(case: CaseSpec, solver: SolverSpec, nx: int | None = None) -> str:
    nx = nx or case.nx
    dx = case.L / nx
    x = np.arange(nx + 1) * dx
    z = case.z(x)
    n = case.n_manning if case.n_manning > 0.0 else N_FRICTIONLESS
    h0 = case.h0(x) if case.h0 is not None else np.zeros_like(x)
    ymax = max_depth(case)
    # Pseudo-2D convention (casespec.py): with width_fn set, BC.q is the
    # TOTAL discharge and each conduit carries its local width B(x_mid).
    if case.width_fn is not None:
        w_link = case.width_fn((np.arange(nx) + 0.5) * dx)
        q_in = case.upstream.q if case.upstream.kind == "inflow_q" else 0.0
    else:
        w_link = np.full(nx, case.W1d)
        q_in = (case.upstream.q * case.W1d
                if case.upstream.kind == "inflow_q" else 0.0)
    assert not (case.rain and solver.virtual_interior), \
        "rain cases need lateral inflows at interior nodes — no VJ column"
    has_outfall = case.downstream.kind in ("stage", "free")

    opts = {
        "FLOW_UNITS": "CMS",
        "FLOW_ROUTING": solver.flow_routing,
        "START_DATE": "01/01/2026", "START_TIME": "00:00:00",
        "REPORT_START_DATE": "01/01/2026", "REPORT_START_TIME": "00:00:00",
        "END_DATE": "01/01/2026", "END_TIME": _hms(case.t_end),
        "ROUTING_STEP": f"{case.dt_routing:g}",
        "REPORT_STEP": _hms(case.report_step),
        "WET_STEP": _hms(case.report_step),
        "DRY_STEP": _hms(case.report_step),
        # normalized physics block — identical for every 1D solver column.
        # Undamped momentum (INERTIAL_DAMPING NONE) is the normalized default:
        # the SWASHES momentum equation carries full convective inertia, so
        # any damping is a scheme approximation, not the benchmark physics.
        # It is paired with a tight Picard convergence budget (MAX_TRIALS 32,
        # HEAD_TOLERANCE 1e-6 m).
        # NODE_CONTINUITY is EXPLICIT (the refactored default = legacy
        # behaviour): legacy warns-and-ignores the key, so SEMI_IMPLICIT made
        # the refactored column silently solve DIFFERENT node continuity —
        # with EXPLICIT the two DW columns are verified BIT-IDENTICAL
        # (2026-08-12 probe: max|dh| = max|dq| = 0 on long-jump, dressler,
        # short-sup). The legacy/refactored parity requirement wins over
        # SEMI_IMPLICIT's extra robustness on frictionless flumes.
        "INERTIAL_DAMPING": "NONE",
        "NODE_CONTINUITY": "EXPLICIT",
        "NORMAL_FLOW_LIMITED": "SLOPE",
        "VARIABLE_STEP": "0",
        "LENGTHENING_STEP": "0",
        "MIN_SURFAREA": "0.01",
        "MAX_TRIALS": "32",
        "HEAD_TOLERANCE": "1e-6",
        "SURCHARGE_METHOD": "EXTRAN",
        "MIN_SLOPE": "0",
        "ALLOW_PONDING": "NO",
        "SKIP_STEADY_STATE": "NO",
        "INFILTRATION": "HORTON",
        "LINK_OFFSETS": "DEPTH",
    }
    opts.update(case.opts_1d)
    opts.update(solver.opts_1d)

    L: list[str] = []
    L.append(f"; SWASHES {case.id} — {case.title} ({case.swashes_ref})")
    L.append(f"; generated by swasheslib.gen1d for solver {solver.id}; "
             f"nx={nx} dx={dx:g} W={case.W1d} n={n:g}")
    L.append("")
    L.append("[TITLE]")
    L.append(f"SWASHES {case.id} / {solver.id}")
    L.append("")
    L.append("[OPTIONS]")
    for k, v in opts.items():
        L.append(f"{k:<22s} {v}")
    L.append("")
    n_junc = nx if has_outfall else nx + 1
    # Virtual-interior solvers: interior chain nodes (exactly two identical
    # zero-offset conduits, no lateral inflow) become [VIRTUAL_JUNCTIONS]
    # (Name + Elev — engine derives geometry from the attached conduits).
    # Node 0 (inflow) and the terminal node stay regular. InitDepths are not
    # representable on virtual nodes; such solvers run dry-start cases only.
    virtual = set()
    if solver.virtual_interior and has_outfall:
        virtual = set(range(1, nx))
    L.append("[JUNCTIONS]")
    L.append(";;Name           InvertElev  MaxDepth  InitDepth  SurDepth  Aponded")
    for i in range(n_junc):
        if i in virtual:
            continue
        L.append(f"{node_id(i):<16s} {z[i]:<11.6f} {ymax:<9.3f} "
                 f"{h0[i]:<10.6f} 0         0")
    L.append("")
    if virtual:
        L.append("[VIRTUAL_JUNCTIONS]")
        L.append(";;Name           InvertElev")
        for i in sorted(virtual):
            L.append(f"{node_id(i):<16s} {z[i]:<11.6f}")
        L.append("")
    L.append("[OUTFALLS]")
    L.append(";;Name           InvertElev  Type   StageData  Gated")
    if has_outfall:
        if case.downstream.kind == "stage":
            L.append(f"{node_id(nx):<16s} {z[nx]:<11.6f} FIXED  "
                     f"{case.downstream.eta:<10.6f} NO")
        else:
            L.append(f"{node_id(nx):<16s} {z[nx]:<11.6f} FREE   "
                     f"           NO")
    else:
        # Closed basin (dam breaks, Thacker): legacy requires >= 1 outlet
        # node (ERROR 145), so add a sacrificial spillway that never engages
        # — its conduit inlet sits at the junction full depth (offset ymax),
        # gated against backflow. Identical deck for every engine.
        L.append(f"{'OUTF':<16s} {z[nx]:<11.6f} FREE              YES")
    L.append("")
    L.append("[CONDUITS]")
    L.append(";;Name           FromNode         ToNode           Length     "
             "Roughness  InOffset  OutOffset  InitFlow  MaxFlow")
    init_flow = 0.0        # SWASHES ICs are at rest (q = 0); flow spins up
    for i in range(nx):
        L.append(f"{link_id(i):<16s} {node_id(i):<16s} {node_id(i + 1):<16s} "
                 f"{dx:<10.6f} {n:<10.3g} 0         0          "
                 f"{init_flow:<9.4f} 0")
    if not has_outfall:
        L.append(f"{'COUT':<16s} {node_id(nx):<16s} {'OUTF':<16s} "
                 f"{dx:<10.6f} {n:<10.3g} {ymax:<9.3f} 0          "
                 f"0.0000    0")
    L.append("")
    L.append("[XSECTIONS]")
    L.append(";;Link           Shape        Geom1     Geom2     Geom3  Geom4  Barrels")
    def _w_txt(w: float) -> str:
        # constant-width cases keep the historical 9.3f (byte-identical
        # decks preserve the run cache); local widths carry 4 decimals
        return f"{w:<9.4f}" if case.width_fn is not None else f"{w:<9.3f}"

    for i in range(nx):
        if case.side_slope > 0.0:
            L.append(f"{link_id(i):<16s} TRAPEZOIDAL  {ymax:<9.3f} "
                     f"{_w_txt(float(w_link[i]))} {case.side_slope:<6.3g} "
                     f"{case.side_slope:<6.3g} 1")
        else:
            L.append(f"{link_id(i):<16s} RECT_OPEN    {ymax:<9.3f} "
                     f"{_w_txt(float(w_link[i]))} 0      0      1")
    if not has_outfall:
        L.append(f"{'COUT':<16s} RECT_OPEN    {ymax:<9.3f} "
                 f"{_w_txt(float(w_link[-1]))} 0      0      1")
    L.append("")
    if case.bend_k > 0.0:
        # Literature miter-bend loss as Kentry on the conduit LEAVING the
        # corner node (the standard user mitigation for planform bends).
        assert case.planform is not None
        s_bend = case.planform.s_bend
        i_bend = int(round(s_bend / dx))
        assert abs(i_bend * dx - s_bend) < 1e-9, "corner must be a node"
        L.append("[LOSSES]")
        L.append(";;Link           Kentry     Kexit      Kavg       FlapGate")
        L.append(f"{link_id(i_bend):<16s} {case.bend_k:<10.4g} 0          "
                 f"0          NO")
        L.append("")
    # One FLOW inflow row per node (SWMM keeps a single external FLOW
    # inflow per node — a second row would override, not add):
    # inflow = Baseline + Sfactor·TS. Rain rides the TS (unit step at
    # rain_start) or the Baseline (rain from t0); upstream q_in merges into
    # node 0's Baseline.
    base = {0: q_in} if q_in > 0.0 else {}
    sfact: dict[int, float] = {}
    need_rain_ts = False
    if case.rain:
        # Uniform rain R0 as lateral inflows: node i owns the half-cells
        # around its station (dx/2 at both domain ends — the outfall's share
        # drains straight through it, keeping total rain = R0·L·W exact).
        w_node = (case.width_fn(x) if case.width_fn is not None
                  else np.full(nx + 1, case.W1d))
        for i in range(nx + 1):
            wgt = 0.5 if i in (0, nx) else 1.0
            q_rain = case.rain * dx * float(w_node[i]) * wgt
            if case.rain_start > 0.0:
                need_rain_ts = True
                sfact[i] = q_rain
            else:
                base[i] = base.get(i, 0.0) + q_rain
    inflow_rows = []
    for i in sorted(set(base) | set(sfact)):
        ts = "RAINTS" if i in sfact else "\"\""
        sf = f"{sfact[i]:<8.6f}" if i in sfact else "1.0     "
        inflow_rows.append(
            f"{node_id(i):<16s} FLOW         {ts:<11s} FLOW  1.0      "
            f"{sf} {base.get(i, 0.0):<9.6f}")
    if inflow_rows:
        L.append("[INFLOWS]")
        L.append(";;Node           Constituent  TimeSeries  Type  Mfactor  "
                 "Sfactor  Baseline  Pattern")
        L.extend(inflow_rows)
        L.append("")
    if need_rain_ts:
        # Unit step at rain_start (1 s linear ramp — SWMM interpolates
        # inflow series linearly); per-node magnitude rides Sfactor.
        t_on = case.rain_start / 3600.0
        L.append("[TIMESERIES]")
        L.append(";;Name           Hours      Value")
        L.append(f"{'RAINTS':<16s} 0.0        0.0")
        L.append(f"{'RAINTS':<16s} {t_on - 1.0 / 3600.0:<10.7f} 0.0")
        L.append(f"{'RAINTS':<16s} {t_on:<10.7f} 1.0")
        L.append(f"{'RAINTS':<16s} 48.0       1.0")
        L.append("")
    if case.planform is not None:
        # Plan coordinates are cosmetic to routing (the planform-blindness
        # under study) but document the bent geometry for GUI/plot review.
        assert abs(case.planform.s_bend / dx - round(case.planform.s_bend / dx)) < 1e-9, \
            "corner must land on a node (no [VERTICES] emission)"
        L.append("[COORDINATES]")
        L.append(";;Node           X-Coord      Y-Coord")
        px, py = case.planform.node_xy(x)
        for i in range(n_junc):
            L.append(f"{node_id(i):<16s} {float(px[i]):<12.4f} "
                     f"{float(py[i]):<12.4f}")
        if has_outfall:
            L.append(f"{node_id(nx):<16s} {float(px[nx]):<12.4f} "
                     f"{float(py[nx]):<12.4f}")
        else:
            L.append(f"{'OUTF':<16s} {float(px[nx]):<12.4f} "
                     f"{float(py[nx]):<12.4f}")
        L.append("")
    L.append("[REPORT]")
    L.append("INPUT      NO")
    L.append("CONTINUITY YES")
    L.append("FLOWSTATS  YES")
    L.append("NODES ALL")
    L.append("LINKS ALL")
    L.append("")
    return "\n".join(L) + "\n"
