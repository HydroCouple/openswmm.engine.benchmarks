#!/usr/bin/env python3
"""Case + SolverSpec -> SWMM .inp deck (SI / CMS, CIRCULAR conduit chain).

One normalized [OPTIONS] block; only FLOW_ROUTING and the per-solver keys
differ between columns (SWASHES fairness precedent). Legacy warns-and-ignores
NODE_CONTINUITY (unknown key) so the shared block is safe for both engines.
"""
from __future__ import annotations

from .cases import Case, link_id, node_id
from .solvers import SolverSpec


def _hms(seconds: float) -> str:
    s = int(round(seconds))
    return f"{s // 3600}:{(s % 3600) // 60:02d}:{s % 60:02d}"


def build_inp(case: Case, solver: SolverSpec) -> str:
    x = case.node_x()
    z = case.node_z()
    conduits = case.conduits()
    n_nodes = len(x)

    opts = {
        "FLOW_UNITS": "CMS",
        "FLOW_ROUTING": solver.flow_routing,
        "START_DATE": "01/01/2026", "START_TIME": "00:00:00",
        "REPORT_START_DATE": "01/01/2026", "REPORT_START_TIME": "00:00:00",
        "END_DATE": "01/01/2026", "END_TIME": _hms(case.t_end),
        "ROUTING_STEP": f"{case.dt_routing:g}",
        "REPORT_STEP": _hms(case.report_step),
        "WET_STEP": _hms(case.report_step),
        "DRY_STEP": _hms(case.report_step),
        "INERTIAL_DAMPING": "NONE",
        # EXPLICIT = the epa_qa legacy-parity config. First-sweep finding:
        # SEMI_IMPLICIT halves the rapid-fill front speed (1.69 vs 2.93 m/s)
        # and leaks +10.4% continuity on the pressurized siphon; legacy
        # ignores the key either way (unknown-key warning).
        "NODE_CONTINUITY": "EXPLICIT",
        "NORMAL_FLOW_LIMITED": "SLOPE",
        "VARIABLE_STEP": "0",
        "LENGTHENING_STEP": "0",
        "MIN_SURFAREA": "0.01",
        "MAX_TRIALS": "32",
        "HEAD_TOLERANCE": "1e-6",
        "SURCHARGE_METHOD": "EXTRAN",
        "MIN_SLOPE": "0",
        "ALLOW_PONDING": "NO",
        "SKIP_STEADY_STATE": "NO",
        "INFILTRATION": "HORTON",
        "LINK_OFFSETS": "DEPTH",
    }
    opts.update(solver.opts)

    L: list[str] = []
    L.append(f"; transitions {case.id} — {case.title}")
    L.append(f"; generated by translib.gen for solver {solver.id}; "
             f"{case.n_conduits} conduits, L={case.L:g} m")
    L.append("")
    L.append("[TITLE]")
    L.append(f"transitions {case.id} / {solver.id}")
    L.append("")
    L.append("[OPTIONS]")
    for k, v in opts.items():
        L.append(f"{k:<22s} {v}")
    L.append("")
    L.append("[JUNCTIONS]")
    L.append(";;Name           InvertElev  MaxDepth  InitDepth  SurDepth  Aponded")
    for i in range(n_nodes - 1):
        L.append(f"{node_id(i):<16s} {z[i]:<11.6f} {case.max_depth:<9.3f} "
                 f"{case.init_depth:<10.6f} 0         0")
    L.append("")
    L.append("[OUTFALLS]")
    L.append(";;Name           InvertElev  Type   StageData  Gated")
    L.append(f"{node_id(n_nodes - 1):<16s} {z[-1]:<11.6f} FIXED  "
             f"{case.outfall_stage:<10.6f} NO")
    L.append("")
    L.append("[CONDUITS]")
    L.append(";;Name           FromNode         ToNode           Length     "
             "Roughness  InOffset  OutOffset  InitFlow  MaxFlow")
    for c in conduits:
        L.append(f"{c['name']:<16s} {node_id(c['i_up']):<16s} "
                 f"{node_id(c['i_dn']):<16s} {c['length']:<10.6f} "
                 f"{c['n']:<10.4g} 0         0          0.0000    0")
    L.append("")
    L.append("[XSECTIONS]")
    L.append(";;Link           Shape        Geom1     Geom2     Geom3  Geom4  Barrels")
    for c in conduits:
        L.append(f"{c['name']:<16s} CIRCULAR     {c['diam']:<9.3f} "
                 f"0         0      0      1")
    L.append("")
    L.append("[INFLOWS]")
    L.append(";;Node           Constituent  TimeSeries  Type  Mfactor  "
             "Sfactor  Baseline  Pattern")
    if case.inflow_const is not None:
        L.append(f"{node_id(0):<16s} FLOW         \"\"          FLOW  1.0      "
                 f"1.0      {case.inflow_const:<9.6f}")
    else:
        L.append(f"{node_id(0):<16s} FLOW         ts_in       FLOW  1.0      "
                 f"1.0      0.0")
    L.append("")
    if case.inflow_ts is not None:
        L.append("[TIMESERIES]")
        L.append(";;Name           Time       Value")
        for minute, q in case.inflow_ts:
            L.append(f"{'ts_in':<16s} {int(minute) // 60}:{int(minute) % 60:02d}"
                     f"       {q:g}")
        L.append("")
    L.append("[REPORT]")
    L.append("INPUT      NO")
    L.append("CONTINUITY YES")
    L.append("FLOWSTATS  YES")
    L.append("NODES ALL")
    L.append("LINKS ALL")
    L.append("")
    return "\n".join(L) + "\n"
